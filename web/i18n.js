let currentLang = "en";

export function t(key) {
  return (DICT[currentLang] && DICT[currentLang][key]) || DICT.en[key] || key;
}

export function getSavedLanguage() {
  try {
    const saved = localStorage.getItem("xotira-lang");
    if (saved && DICT[saved]) return saved;
  } catch {}
  return "en";
}

export function applyLanguage(code) {
  const lang = DICT[code] ? code : "en";
  currentLang = lang;
  const meta = LANGUAGES.find(l => l.code === lang) || LANGUAGES[0];
  document.documentElement.lang = lang;
  document.documentElement.dir = meta.dir;
  try { localStorage.setItem("xotira-lang", lang); } catch {}

  for (const [id, key] of Object.entries(ID_MAP)) {
    const el = document.getElementById(id);
    if (el) el.textContent = t(key);
  }
  for (const [id, key] of Object.entries(PH_MAP)) {
    const el = document.getElementById(id);
    if (el) el.placeholder = t(key);
  }
  const cmdSpan = document.querySelector("#open-cmd > span");
  if (cmdSpan) cmdSpan.textContent = t("cmd-search");

  for (const el of document.querySelectorAll("[data-i18n]")) {
    const key = el.dataset.i18n;
    if (key) el.textContent = t(key);
  }
  for (const el of document.querySelectorAll("[data-i18n-ph]")) {
    const key = el.dataset.i18nPh;
    if (key) el.placeholder = t(key);
  }
  window.dispatchEvent(new CustomEvent("xotira-lang-change", {detail: {lang}}));
  return lang;
}

const A11Y_KEY = "xotira-a11y";

export function loadA11y() {
  try {
    return {fontScale: "100", lineHeight: "1.68", dyslexia: false, highContrast: false, ...JSON.parse(localStorage.getItem(A11Y_KEY) || "{}")};
  } catch {
    return {fontScale: "100", lineHeight: "1.68", dyslexia: false, highContrast: false};
  }
}

export function applyA11y(prefs) {
  const clean = {
    fontScale: ["90", "100", "112", "125"].includes(String(prefs.fontScale)) ? String(prefs.fontScale) : "100",
    lineHeight: ["1.5", "1.68", "1.95"].includes(String(prefs.lineHeight)) ? String(prefs.lineHeight) : "1.68",
    dyslexia: Boolean(prefs.dyslexia),
    highContrast: Boolean(prefs.highContrast),
  };
  const root = document.documentElement;
  root.style.setProperty("--reader-font-scale", `${Number(clean.fontScale) / 100}`);
  root.style.setProperty("--reader-line-height", clean.lineHeight);
  root.dataset.dyslexia = clean.dyslexia ? "true" : "false";
  root.dataset.contrast = clean.highContrast ? "high" : "normal";
  try { localStorage.setItem(A11Y_KEY, JSON.stringify(clean)); } catch {}
  return clean;
}
